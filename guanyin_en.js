/* 把中文解曰翻译为英文（按“。”拆分，逐句匹配） */
function translateJie(zhi) {
  if (!zhi) return '';
  return zhi.split('。').map(s => s.trim()).filter(Boolean).map(clause => {
    if (JIE_EN[clause]) return JIE_EN[clause];
    // 类别前缀匹配
    for (const pre in JIE_PREFIX_EN) {
      if (clause.indexOf(pre) === 0) {
        const rest = clause.slice(pre.length);
        if (JIE_PREFIX_EN[pre][rest]) return JIE_PREFIX_EN[pre][rest];
      }
    }
    return clause; // 兜底：保留中文
  }).join(' ');
}
